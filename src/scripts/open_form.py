def rewrite_cond(cond: str):
    """Новое условие и вид ответа (или (cond, None), если менять нечего)."""
    t, keep = protect(cond)
    kind = None
    for pat, rep, k in RULES:
        new = re.sub(pat, rep, t, count=1)
        if new != t:
            t = new
            kind = kind or k
    return unprotect(t, keep), kind


WORDS = {"prov": ("доказуема", "недоказуема"), "taut": ("тавтология", "не тавтология")}


def rewrite_ans(ans: str, kind: str | None) -> str:
    if kind:
        yes, no = WORDS[kind.rstrip("1")] if kind != "student" else ("", "")
        if yes:
            ans = re.sub(r"— да\b", "— " + yes, ans)
            ans = re.sub(r"— нет\b", "— " + no, ans)
    if kind in ("prov", "taut"):
        yes, no = WORDS[kind]
        ans = re.sub(r"(?<=[а-ж]\) )да\b", yes, ans)
        ans = re.sub(r"(?<=[а-ж]\) )нет\b", no, ans)
    elif kind in ("prov1", "taut1"):
        yes, no = WORDS[kind[:-1]]
        ans = re.sub(r"^Да\b", yes.capitalize(), ans)
        ans = re.sub(r"^Нет\b", no.capitalize(), ans)
    return ans


SEC_RX = re.compile(r"(## Условие\n\n)(.*?)(\n\n## Ответ\n\n)(.*?)(\n\n## Решение|\Z)", re.S)


def process(text: str):
    changed = 0

    def fix(m):
        nonlocal changed
        cond, ans = m.group(2), m.group(4)
        if not test_like(cond):
            return m.group(0)
        new_cond, kind = rewrite_cond(cond)
        new_ans = rewrite_ans(ans, kind)
        if (new_cond, new_ans) != (cond, ans):
            changed += 1
        return m.group(1) + new_cond + m.group(3) + new_ans + m.group(5)
    return SEC_RX.sub(fix, text), changed


def cards(text: str):
    for m in SEC_RX.finditer(text):
        yield m.group(2), m.group(4)


def main() -> int:
    apply = "--apply" in sys.argv
    left, total = [], 0
    for folder in FILES:
        for f in sorted((DATA / folder).glob("*.md")):
            text = f.read_text(encoding="utf-8")
            if apply:
                text, n = process(text)
                total += n
                if n:
                    f.write_text(text, encoding="utf-8")
            for chunk in re.split(r"\n=====\n", text):
                m = re.search(r'^id: "?([^"\n]+)"?', chunk, re.M)
                for cond, _ in cards(chunk):
                    if test_like(cond):
                        left.append((m.group(1) if m else f.name, cond))
    if apply:
        print(f"Переписано задач: {total}")
    for cid, cond in left[: (10 ** 6 if "-v" in sys.argv else 15)]:
        print(f"{cid}: {re.sub(chr(10), ' ', cond)[:220]}")
    print(f"Задач в «тестовой» форме: {len(left)}")
    return 1 if left else 0


if __name__ == "__main__":
    sys.exit(main())
