def protect(text: str):
    keep = []

    def put(m):
        keep.append(m.group(0))
        return f"⟦{len(keep) - 1}⟧"
    return re.sub(r"\$\$.+?\$\$|\$[^$\n]+\$", put, text, flags=re.S), keep


def unprotect(text: str, keep: list) -> str:
    return re.sub(r"⟦(\d+)⟧", lambda m: keep[int(m.group(1))], text)


def test_like(cond: str) -> bool:
    t, _ = protect(cond)
    return bool(TEST_RX.search(t))


