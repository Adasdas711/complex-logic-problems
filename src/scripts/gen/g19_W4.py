def card(sec, meta, cond, ans, sol):
    m = {"chapter": 19, "section": sec}
    m.update(meta)
    m.setdefault("generated", True)
    head = ["---"]
    for k in ["chapter", "section", "level", "type", "step", "condition", "form", "answer", "source", "case",
              "series", "generated", "tags"]:
        if k in m and m[k] is not None:
            v = m[k]
            if k == "source":
                v = f'"{v}"'
            elif k == "tags":
                v = "[" + ", ".join(v) + "]"
            elif isinstance(v, bool):
                v = "true" if v else "false"
            head.append(f"{k}: {v}")
    head.append("---")
    text = "\n".join(head) + f"\n\n## Условие\n\n{cond.strip()}\n\n## Ответ\n\n{ans.strip()}\n\n## Решение\n\n{sol.strip()}\n"
    CARDS.setdefault(sec, []).append(text)


def D(f):
    return "$" + tex(f) + "$"


def proof_text(lines, names, blanks=(), blank_rules=()):
    """Строки вывода в оформлении книги. blanks — номера строк без формулы, blank_rules — без основания."""
    out = []
    for i, (f, rule, refs) in enumerate(lines, 1):
        fs = "___" if i in blanks else D(f)
        rs = names.get((i, rule), names.get(rule, rule))
        if refs:
            basis = ", ".join(map(str, refs)) + "; " + rs
        else:
            basis = rs
        if i in blank_rules:
            basis = "___"
        out.append(f"{i}. {fs} [{basis}].")
    return "\n".join(out)


def must(lines, premises=()):
    bad = check_lines(lines, premises)
    if bad:
        raise SystemExit(f"неверные строки {bad}: " + "; ".join(tex(lines[b - 1][0]) for b in bad))


