GENERIC = {"Можно": "Выясните", "Следует": "Выясните", "Правомерно": "Оцените", "Совместимы": "Выясните"}
YESNO_VERB = {"Образуют": "образуют", "Существует": "существует", "Находится": "находится", "Соприкасаются": "соприкасаются",
              "Индивидуален": "индивидуален", "Непрерывен": "непрерывен", "Соответствует": "соответствует",
              "Является": "является", "Возможно": "возможно", "Задан": "задан", "Становятся": "становятся"}


def _apply_manual(cond, ans):
    for key, old, new, amap in MANUAL:
        if key not in cond or old is None:
            continue
        def expand(m):
            return re.sub(r"\\(\d)", lambda g: m.group(int(g.group(1))), new).replace("\\\\", "\\")
        cond2 = cond.replace(old, new, 1) if old in cond else re.sub(old, expand, cond, count=1, flags=re.S)
        if cond2 == cond:
            raise ValueError(f"замена не сработала: {key}")
        cond = cond2
        for a, b in amap.items():
            if ans.startswith(a):
                ans = b + ans[len(a):]
        break
    return cond, ans


def rewrite(cond: str, ans: str):
    cond, ans = _apply_manual(cond, ans)
    # «Что истинно: X, Y или Z?» / «Что верно: X или Y?»
    cond = re.sub(r"Что (истинно|верно): (\$[^$]*\$), (\$[^$]*\$) или (\$[^$]*\$)\?",
                  r"Установите, какое из высказываний \2, \3, \4 истинно, и обоснуйте.", cond)
    cond = re.sub(r"Что (истинно|верно): (\$[^$]*\$) или (\$[^$]*\$)\?",
                  r"Установите, какое из высказываний \2, \3 истинно, и обоснуйте.", cond)
    # «… Верно ли это?» после утверждения студента
    m = re.search(r"Верно ли это(?: применение)?( с точки зрения § \d+)?\?", cond)
    if m:
        cond = cond[:m.start()] + (f"Проверьте это утверждение{m.group(1) or ''} и обоснуйте вывод; если оно ошибочно, "
                                   "назовите нарушенное правило книги.") + cond[m.end():]
        ans = re.sub(r"^Нет([:,])", r"Утверждение неверно\1", ans)
        ans = re.sub(r"^Да([:,])", r"Утверждение верно\1", ans)
    # «Глагол ли …?» → «Установите, глагол ли …, и обоснуйте ответ.»
    t, keep = protect(cond)

    def gen(mm):
        verb, rest = mm.group(1), mm.group(2)
        lead = GENERIC.get(verb, "Установите")
        return f"{lead}, {verb.lower()} ли {rest}, и обоснуйте ответ."
    t2 = re.sub(r"(?:(?<=^)|(?<=[.:;!?»]\s)|(?<=\n))([А-ЯЁ][а-яё]+) ли ([^?\n]+)\?", gen, t)
    if t2 != t:
        vm = re.search(r"(?:^|[.:;!?»]\s|\n)([А-ЯЁ][а-яё]+) ли ", t)
        verb = vm.group(1) if vm else ""
        cond = unprotect(t2, keep)
        if verb in YESNO_VERB:
            v = YESNO_VERB[verb]
            ans = re.sub(r"^Да\b", v.capitalize(), ans)
            ans = re.sub(r"^Нет\b", "Не " + v, ans)
    # ответы серий — словами
    if "истинно оно или ложно" in cond:
        ans = re.sub(r"(?<=[а-ж]\) )да\b", "истинно", ans)
        ans = re.sub(r"(?<=[а-ж]\) )нет\b", "ложно", ans)
    if "и если является — собственной ли" in cond:
        ans = {"Да; собственной.": "Является, собственной.", "Да, но не собственной.": "Является, но не собственной.",
               "Нет.": "Не является."}.get(ans, ans)
    if "поставлен ли класс $B$ в соответствие" in cond:
        ans = re.sub(r"^Да\.", "Поставлен.", ans)
        ans = re.sub(r"^Нет:", "Не поставлен:", ans)
    if "совместимы ли эти данные" in cond:
        cond = cond.replace("Если нет — какое правило нарушено?", "Если несовместимы, назовите нарушенное правило.")
        ans = re.sub(r"^Нет:", "Несовместимы:", ans)
    ans = ans.replace("Не непрерывен, $A$ прерывен.", "Прерывен.")
    return cond, ans


SEC_RX = re.compile(r"(## Условие\n\n)(.*?)(\n\n## Ответ\n\n)(.*?)(\n\n## Решение)", re.S)


def process_card(text: str) -> str:
    m = SEC_RX.search(text)
    if not m:
        return text
    cond, ans = rewrite(m.group(2), m.group(4))
    return text[:m.start()] + m.group(1) + cond + m.group(3) + ans + m.group(5) + text[m.end():]


def main():
    p = ROOT / "data" / "zadachi" / "18.md"
    chunks = re.split(r"(\n=====\n)", p.read_text(encoding="utf-8"))
    out = [process_card(c) if "## Условие" in c else c for c in chunks]
    p.write_text("".join(out), encoding="utf-8")


if __name__ == "__main__":
    main()
